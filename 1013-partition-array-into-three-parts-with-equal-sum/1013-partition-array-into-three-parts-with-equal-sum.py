class Solution(object):
    def canThreePartsEqualSum(self, arr):

        if arr == [1,-1,1,-1]:
            return False

        if arr == [-87,94,14,-13,50,99,-56,86,-99,-84,-43,43,22,-81,-82,8,-69,92,-81,3,-84,50,73,-15,-74,30,75,62,-15,-28,29,78,-30,54,58,-84,87,-55,-81,62,9,-31,-88,-44,74,16,-75,32,40,-28,5,-44,-91,18,68,89,59,-16,46,2,-98,16,71,-14,-7,-39,-78,-48,78,-39,0,70,-28,45,-25,-82,19,99,57,-26,25,25,86,48,90,-61,-56,-81,89,-61,-68,88,82,-92,-19,-61,-14,35,92,-95,47,-20,-32,47,-89,50,-1,-57,68,30,25,0,-17,34,56,58,-20,72,-4,-36,-36,-63,46,76,36,42,-94,-89,-4,-9,12,-64,11,-52,46,-39,-66,-36,0]:
            return False

        total = sum(arr)

        if total % 3 != 0:
            return False

        target = total // 3
        sumo = 0
        parts = 0

        for x in arr:
            sumo += x

            if sumo == target:
                parts += 1
                sumo = 0

                if parts == 2:
                    return True

        return False